def bullets(slide, items, *, x=Inches(0.9), y=Inches(2.0), w=Inches(11.5),
            size=15, gap=0.62):
    for i, item in enumerate(items):
        top = y + Inches(gap * i)
        head, detail = item if isinstance(item, tuple) else (item, None)
        rect(slide, x, top + Inches(0.11), Inches(0.1), Inches(0.1), BLUE)
        text(slide, x + Inches(0.3), top - Inches(0.04), w - Inches(0.3), Inches(0.34),
             head, size=size, color=INK, bold=True)
        if detail:
            text(slide, x + Inches(0.3), top + Inches(0.3), w - Inches(0.3), Inches(0.5),
                 detail, size=size - 3, color=MUTED, line=1.35)


def stat_row(slide, stats, y, height):
    n = len(stats)
    gap = Inches(0.22)
    card_w = int((Inches(11.6) - gap * (n - 1)) / n)
    for i, (value, label, colour) in enumerate(stats):
        x = Inches(0.85) + i * (card_w + gap)
        rect(slide, x, y, card_w, height, BLUE_PALE, radius=0.08)
        text(slide, x, y + Inches(0.2), card_w, Inches(0.6),
             value, size=30, color=colour, bold=True, align=PP_ALIGN.CENTER)
        text(slide, x, y + Inches(0.88), card_w, Inches(0.4),
             label, size=12, color=MUTED, align=PP_ALIGN.CENTER)


