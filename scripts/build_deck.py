def text(slide, x, y, w, h, content, *, size=14, color=BODY, bold=False,
         align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP, line=1.35):
    box = slide.shapes.add_textbox(x, y, w, h)
    frame = box.text_frame
    frame.word_wrap = True
    frame.vertical_anchor = anchor
    # python-pptx leaves the default left/right inset (0.1in each) on a textbox, so text starts
    # 0.1in right of the box and wraps 0.2in early. On a table built from positioned textboxes
    # that shifted every column, and the error accumulated across the row. Zeroed so the box
    # geometry is the text geometry.
    frame.margin_left = 0
    frame.margin_right = 0
    frame.margin_top = 0
    frame.margin_bottom = 0
    items = content if isinstance(content, list) else [content]
    for i, item in enumerate(items):
        para = frame.paragraphs[0] if i == 0 else frame.add_paragraph()
        para.alignment = align
        para.line_spacing = line
        label, opts = item if isinstance(item, tuple) else (item, {})
        run = para.add_run()
        run.text = label
        run.font.size = Pt(opts.get("size", size))
        run.font.bold = opts.get("bold", bold)
        run.font.color.rgb = opts.get("color", color)
        run.font.name = opts.get("font", FONT)
    return box


def rect(slide, x, y, w, h, fill, *, line_color=None, radius=None):
    shape = slide.shapes.add_shape(
        MSO_SHAPE.ROUNDED_RECTANGLE if radius else MSO_SHAPE.RECTANGLE, x, y, w, h
    )
    shape.fill.solid()
    shape.fill.fore_color.rgb = fill
    if line_color is None:
        shape.line.fill.background()
    else:
        shape.line.color.rgb = line_color
        shape.line.width = Pt(1)
    if radius:
        shape.adjustments[0] = radius
    shape.shadow.inherit = False
    return shape


